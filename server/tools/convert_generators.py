"""Convert the PHP schedule generator tables to a Python module.

The output is racing/engine/scheduling/generator_tables.py.

    python tools/convert_generators.py            # write the module
    python tools/convert_generators.py --check    # fail if the module differs

The sources are website/inc/generators/{2,3,4,5,6,8}-lanes.inc. Each is a run
of make_scheduler_data(nlanes, ncars, generators, ...permutation_sets) calls
whose arguments are integers and nested array(...) literals. Anything else is
an error naming the file and line. Entries keep their source order.
"""

import argparse
import json
import re
import sys
from pathlib import Path

SERVER_DIR = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = SERVER_DIR.parent / "website" / "inc" / "generators"
DEFAULT_OUTPUT = SERVER_DIR / "racing" / "engine" / "scheduling" / "generator_tables.py"
LANE_COUNTS = (2, 3, 4, 5, 6, 8)

HEADER = (
    "# Generated by server/tools/convert_generators.py from "
    "website/inc/generators/*.inc. Do not edit.\n"
)

TOKEN = re.compile(
    r"""
    (?P<skip>\s+|//[^\n]*)
    |(?P<open_tag><\?php)
    |(?P<close_tag>\?>)
    |(?P<name>[A-Za-z_]\w*)
    |(?P<int>\d+)
    |(?P<punct>[(),;])
    """,
    re.VERBOSE,
)


class ConvertError(Exception):
    pass


def tokenize(path, text):
    """Return (kind, text, line) tokens, with whitespace and // comments dropped."""
    tokens = []
    pos = 0
    line = 1
    while pos < len(text):
        m = TOKEN.match(text, pos)
        misplaced = (m and m.lastgroup == "open_tag" and pos != 0) or (
            m and m.lastgroup == "close_tag" and text[m.end() :].strip()
        )
        if m is None or misplaced:
            snippet = text[pos : pos + 20].split("\n")[0]
            raise ConvertError(f"{path}:{line}: unexpected {snippet!r}")
        if m.lastgroup != "skip":
            tokens.append((m.lastgroup, m.group(), line))
        line += m.group().count("\n")
        pos = m.end()
    return tokens


class Parser:
    def __init__(self, path, tokens):
        self.path = path
        self.tokens = tokens
        self.i = 0

    def fail(self, message, line=None):
        if line is None:
            line = self.tokens[min(self.i, len(self.tokens) - 1)][2]
        raise ConvertError(f"{self.path}:{line}: {message}")

    def peek_text(self):
        return self.tokens[self.i][1] if self.i < len(self.tokens) else None

    def take(self, kind, text=None):
        if self.i >= len(self.tokens):
            self.fail(f"unexpected end of file, expected {text or kind}")
        tok = self.tokens[self.i]
        if tok[0] != kind or (text is not None and tok[1] != text):
            self.fail(f"expected {text or kind}, found {tok[1]!r}", tok[2])
        self.i += 1
        return tok[1]

    def value(self):
        if self.i < len(self.tokens) and self.tokens[self.i][0] == "int":
            return int(self.take("int"))
        self.take("name", "array")
        self.take("punct", "(")
        items = []
        while self.peek_text() != ")":
            items.append(self.value())
            if self.peek_text() == ",":
                self.i += 1
            elif self.peek_text() != ")":
                self.fail(f"expected ',' or ')', found {self.peek_text()!r}")
        self.take("punct", ")")
        return items

    def calls(self):
        """Yield (line, [argument, ...]) for each make_scheduler_data call."""
        while self.i < len(self.tokens) and self.tokens[self.i][0] != "close_tag":
            line = self.tokens[self.i][2]
            self.take("name", "make_scheduler_data")
            self.take("punct", "(")
            args = [self.value()]
            while self.peek_text() == ",":
                self.i += 1
                args.append(self.value())
            self.take("punct", ")")
            self.take("punct", ";")
            yield line, args


def parse_file(path, nlanes):
    """Return {ncars: {"generators": [...], "permutation_sets": [...]}}, in order."""
    parser = Parser(path, tokenize(path, path.read_text(encoding="utf-8")))
    parser.take("open_tag")
    table = {}
    for line, args in parser.calls():
        if len(args) < 3 or not all(isinstance(a, int) for a in args[:2]):
            parser.fail("make_scheduler_data needs nlanes, ncars, generators", line)
        if args[0] != nlanes:
            parser.fail(f"nlanes {args[0]} in a {nlanes}-lane file", line)
        if not isinstance(args[2], list):
            parser.fail("generators is not an array", line)
        if args[1] in table:
            parser.fail(f"duplicate entry for {nlanes} lanes, {args[1]} cars", line)
        table[args[1]] = {"generators": args[2], "permutation_sets": args[3:]}
    return table


def render(source_dir):
    lines = [HEADER, "from json import loads\n\nGENERATOR_TABLES = {\n"]
    for nlanes in LANE_COUNTS:
        table = parse_file(source_dir / f"{nlanes}-lanes.inc", nlanes)
        lines.append(f"    {nlanes}: {{\n")
        for ncars, entry in table.items():
            text = json.dumps(entry, separators=(",", ":"))
            lines.append(f"        {ncars}: loads('{text}'),\n")
        lines.append("    },\n")
    lines.append("}\n")
    return "".join(lines).encode("utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the output file differs from a fresh conversion",
    )
    ap.add_argument(
        "--source", type=Path, default=DEFAULT_SOURCE, help="folder holding N-lanes.inc"
    )
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args(argv)

    try:
        generated = render(args.source)
    except (ConvertError, OSError) as e:
        print(f"convert_generators: {e}", file=sys.stderr)
        return 2

    if args.check:
        if args.output.exists() and args.output.read_bytes() == generated:
            return 0
        print(
            f"convert_generators: {args.output} is out of date; "
            "run server/tools/convert_generators.py and commit the result",
            file=sys.stderr,
        )
        return 1

    args.output.write_bytes(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
