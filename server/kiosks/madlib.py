def madlib(address: str) -> str:
    """PHP's `abs(crc32($addr))` is the unsigned CRC-32 on a 64-bit build."""
    crc = zlib.crc32(address.encode())
    return f"{ADJECTIVES[crc % len(ADJECTIVES)]} {NOUNS[(crc >> 16) % len(NOUNS)]}"
